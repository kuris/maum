if (typeof window !== 'undefined') {
  window.MAUM_DATA = MAUM_DATA;
  window.getTodayMaumDaily = getTodayMaumDaily;
  window.getDailyByDayIndex = getDailyByDayIndex;
  window.getRandomMindCard = getRandomMindCard;
}
