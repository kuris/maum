// 유틸리티 함수: 오늘 날짜 기준 데일리 성찰 가져오기
function getTodayMaumDaily() {
  const now = new Date();
  const day = now.getDate(); // 1 ~ 31
  const item = MAUM_DATA.daily.find(d => d.dayIndex === day) || MAUM_DATA.daily[0];
  return {
    ...item,
    formattedDate: `${now.getFullYear()}년 ${now.getMonth() + 1}월 ${now.getDate()}일`
  };
}

// 특정 일자의 데일리 성찰 가져오기
function getDailyByDayIndex(dayIdx) {
  const idx = Math.max(1, Math.min(31, parseInt(dayIdx, 10) || 1));
  return MAUM_DATA.daily.find(d => d.dayIndex === idx) || MAUM_DATA.daily[0];
}

// 랜덤 마음 카드 뽑기
function getRandomMindCard(themeFilter = null) {
  let list = MAUM_DATA.cards;
  if (themeFilter && themeFilter !== 'all') {
    list = list.filter(c => c.theme === themeFilter);
  }
  const randomIndex = Math.floor(Math.random() * list.length);
  return list[randomIndex];
}

